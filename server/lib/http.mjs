// The public domain's home page is the Close the Loop landing (public/home.html, also at /home on every host); the desk
// console stays at / on valun-desk.fly.dev and every other host. A local server runs no desk (fix inbox #143): its / is
// the landing too, on any host.
const HOME_HOSTS = new Set(['valun.tech', 'www.valun.tech']);
const HTML = 'text/html; charset=utf-8';
const TYPES = {'.md': 'text/markdown; charset=utf-8', '.txt': 'text/plain; charset=utf-8', '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.png': 'image/png', '.svg': 'image/svg+xml', '.woff2': 'font/woff2', '.json': 'application/json; charset=utf-8'};
const SEC_HEADERS = {
  'Content-Security-Policy': "default-src 'self'; img-src 'self' data:; style-src 'self'; script-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'",
  'X-Content-Type-Options': 'nosniff', 'Referrer-Policy': 'no-referrer', 'Cache-Control': 'no-store',
};
// What /api/* answers while the legacy desk is unavailable beside the network, and what /mcp's JSON-RPC error says then
// (fix inbox #64; deskAvailable below).
export const DESK_UNAVAILABLE = Object.freeze({error: 'desk_unavailable',
  message: 'the synthetic demo desk is unavailable: its demo tracker is starting, stopped or not answering (fix inbox #64); the Valun network is under /pilot/v1 (see /skill.md)'});

// deskAvailable (server.mjs, fix inbox #64): beside the network the legacy synthetic desk (/api, /mcp) is optional, and
// this says whether it can answer now. While it says no, nothing reaches the service or the MCP tools: every /api/*
// request answers 503 desk_unavailable before anything else is checked, and a POST to /mcp that passes the transport's
// own checks answers 503 in JSON-RPC (mcpEndpoint). null (the desk alone, and the tests): no such check, every desk
// request is handled as before.
export function createHandler({service, mcp, cfg, publicDir, pilotRoutes = null, a2a = null, deskAvailable = null}) {
  const send = (res, status, body, type = 'application/json; charset=utf-8', extra = {}) => {
    // Every HTML page leaves through here, the files of public/ and the rendered ones alike (the pilot's routes are
    // handed this send): on staging and on a local server each opens with its banner (lib/environment.mjs); elsewhere
    // it goes as it is.
    if (type.startsWith('text/html')) body = withBanner(body, BANNER);
    const payload = body == null ? '' : typeof body === 'string' || Buffer.isBuffer(body) ? body : JSON.stringify(body, null, 1);
    // Every answer says its length (Content-Length; none on a 204 or 304, which have no body). writeHead before end()
    // made Node frame each body as chunked, so a client could read every byte of an answer and still fail on the
    // missing last chunk when a connection between it and this server ended early (http.client: IncompleteRead with
    // the whole body read).
    const length = status === 204 || status === 304 ? {} : {'Content-Length': Buffer.byteLength(payload)};
    res.writeHead(status, {'Content-Type': type, ...SEC_HEADERS, ...extra, ...length});
    res.end(payload);
  };
  async function readBody(req, limit) {
    let size = 0; const chunks = [];
    for await (const c of req) { size += c.length; if (size > limit) throw new UserError('request body too large', 413); chunks.push(c); }
    return Buffer.concat(chunks).toString('utf8');
  }
  async function readJson(req) {
    const t = await readBody(req, 16_384);
    if (!t) return {};
    try { return JSON.parse(t); } catch { throw new UserError('body must be JSON'); }
  }
  // Behind Fly's proxy every request comes from the proxy; the client address is in Fly-Client-IP. Every per-address limit
  // keys on ipKey (fix inbox #21): an IPv6 client by its /64, which one host or one customer controls as a whole.
  const clientIp = req => ipKey((cfg.trustFlyClientIp && req.headers['fly-client-ip']) || req.socket.remoteAddress || '?', 64);
  const hits = new Map();
  const rateLimited = ip => {
    const now = Date.now(), w = (hits.get(ip) || []).filter(t => now - t < 600_000);
    w.push(now); hits.set(ip, w);
    if (hits.size > 5000) for (const [k, v] of hits) if (!v.some(t => now - t < 600_000)) hits.delete(k);
    return w.length > 120;
  };
  // The legacy synthetic desk (/api, /mcp) on a hosted deployment with no demo passphrase is read-only (fix inbox #64):
  // its writes used server-held keys on the demo tracker the network's process depends on, open to anyone. Without a
  // passphrase, writes are open only to a local or test deployment.
  const writesClosed = cfg.deployment === 'hosted' && !cfg.writeToken;
  const tokenOk = got => {
    if (!cfg.writeToken) return !writesClosed;
    const a = Buffer.from(String(got || '')), b = Buffer.from(cfg.writeToken);
    return a.length === b.length && crypto.timingSafeEqual(a, b);
  };
  const requestToken = req => req.headers['x-valun-token'] || (/^Bearer\s+(.+)$/i.exec(req.headers.authorization || '') || [])[1];

  async function mcpEndpoint(req, res) {
    if (req.method !== 'POST') return send(res, 405, {error: 'POST JSON-RPC messages to this endpoint (stateless Streamable HTTP; no SSE stream)'}, undefined, {Allow: 'POST'});
    // DNS-rebinding guard: a browser page from another site must not drive this endpoint.
    const origin = req.headers.origin;
    let sameOrigin = !origin;
    try { sameOrigin ||= new URL(origin).host === req.headers.host; } catch { /* "null" or malformed origin */ }
    if (!sameOrigin) return send(res, 403, {error: 'cross-origin requests are not allowed'});
    const pv = req.headers['mcp-protocol-version'];
    if (pv && !PROTOCOL_VERSIONS.includes(pv)) return send(res, 400, {jsonrpc: '2.0', id: null, error: {code: -32600, message: `unsupported MCP-Protocol-Version ${pv}`}});
    let body;
    try { body = JSON.parse(await readBody(req, 65_536)); } catch (e) {
      return send(res, e instanceof UserError ? 413 : 400, {jsonrpc: '2.0', id: null, error: {code: -32700, message: e instanceof UserError ? e.message : 'parse error'}});
    }
    const ip = clientIp(req);
    const ctx = {writeAllowed: tokenOk(requestToken(req)), writesClosed, rateLimited: () => rateLimited(ip)};
    const msgs = Array.isArray(body) ? body : [body];
    // The desk unavailable (deskAvailable, fix inbox #64): no message reaches the MCP tools, and the answer is HTTP 503
    // in JSON-RPC. Each message handle() would answer gets the desk_unavailable error with its own id
    // (unavailableReply); notifications get none, and a body of nothing but notifications gets an empty 503. A client
    // that passes the body on as it comes (scripts/valun-mcp-stdio.mjs) then gets an answer to each request it sent.
    if (deskAvailable && !(await deskAvailable())) {
      const out = msgs.map(m => unavailableReply(m, DESK_UNAVAILABLE)).filter(Boolean);
      return send(res, 503, !out.length ? null : Array.isArray(body) ? out : out[0]);
    }
    const out = (await Promise.all(msgs.map(m => mcp.handle(m, ctx)))).filter(Boolean);
    if (!out.length) return send(res, 202, null);
    return send(res, 200, Array.isArray(body) ? out : out[0]);
  }

  async function route(req, res) {
    const url = new URL(req.url, 'http://x'), p = url.pathname;
    // A HEAD is answered as a GET on the pages and files served here, /llms.txt, the A2A front door's reads and the
    // network's public reads (fix inbox #142): the same status and headers, Content-Length included (send() counts the
    // body the GET would get), and no body, which Node leaves out of an answer to HEAD. Uptime monitors, link checkers and
    // `curl -I` see what a GET sees. A HEAD never reaches a write: the pilot's routes answer it only on their public reads,
    // and never authenticate it (lib/pilot/http.mjs). The legacy desk's /api answers GET only, as before.
    const GH = req.method === 'GET' || req.method === 'HEAD';
    if (p === '/' && GH && (LOCAL || HOME_HOSTS.has(String(req.headers.host || '').toLowerCase().replace(/:\d+$/, '')))) {
      return send(res, 200, fs.readFileSync(path.join(publicDir, 'home.html')), HTML);
    }
    // A loop card (lib/pilot/loops.mjs): server-rendered with its Open Graph tags, for link previews.
    let lm;
    if (GH && (lm = /^\/loop\/([^/]{1,64})$/.exec(p))) {
      if (pilotRoutes?.loopPage) return pilotRoutes.loopPage(req, res, lm[1], send, clientIp);
      return send(res, 404, renderLoopNotFound(), HTML);
    }
    // The open-source maintainers page (lib/pilot/agents.mjs), static text in the shell of the loop cards.
    if (GH && p === '/maintainers') return send(res, 200, renderMaintainersPage(), HTML);
    // An agent's public page (lib/pilot/agents.mjs), server-rendered with its Open Graph tags, for sharing.
    if (GH && (lm = /^\/agent\/([^/]{1,64})$/.exec(p))) {
      if (pilotRoutes?.agentPage) return pilotRoutes.agentPage(req, res, lm[1], send, clientIp);
      return send(res, 404, renderAgentNotFound(), HTML);
    }
    // The A2A front door (lib/a2a.mjs): the Agent Card and the JSON-RPC endpoint, with their own CORS and rate limit.
    if (a2a && A2A_PATHS.has(p)) return a2a(req, res, p, send, clientIp);
    if (GH && p === '/llms.txt') return send(res, 200, LOCAL ? withLocalPreface(llmsText(publicDir), PUBLIC_ORIGIN) : llmsText(publicDir), TYPES['.txt']);
    if (GH && STATIC.has(p)) {
      const f = STATIC.get(p), file = fs.readFileSync(path.join(publicDir, f));
      return send(res, 200, LOCAL && f === SKILL_FILE ? withLocalPreface(file, PUBLIC_ORIGIN) : file, TYPES[path.extname(f)]);
    }
    if (p === '/mcp') return mcpEndpoint(req, res);
    if (pilotRoutes && p.startsWith('/pilot/v1/')) {
      const cors = publicRead(req);
      return pilotRoutes(req, res, url, cors ? (r, status, body, type, extra = {}) => send(r, status, body, type, {...cors, ...extra}) : send, clientIp);
    }
    if (!p.startsWith('/api/')) return send(res, 404, {error: 'not found'});
    if (deskAvailable && !(await deskAvailable())) return send(res, 503, DESK_UNAVAILABLE);
    if (req.method === 'POST') {
      if (writesClosed) return send(res, 403, {error: 'writes_closed', message: 'the synthetic demo desk is read-only on this hosted deployment (fix inbox #64); the Valun network is under /pilot/v1 (see /skill.md)'});
      if (!tokenOk(requestToken(req))) return send(res, 401, {error: 'this deployment requires the demo write token (x-valun-token)'});
      if (rateLimited(clientIp(req))) return send(res, 429, {error: 'too many changes from this address; try again in a few minutes'});
    }
    let m;
    const G = req.method === 'GET', P = req.method === 'POST';
    if (G && p === '/api/status') return send(res, 200, await service.status());
    if (G && p === '/api/participants') return send(res, 200, await service.participants());
    if (P && p === '/api/participants') return send(res, 201, await service.createParticipant(await readJson(req)));
    if (P && (m = /^\/api\/participants\/(p-\d{4})\/policy$/.exec(p))) return send(res, 200, await service.setPolicy(m[1], await readJson(req)));
    if (G && p === '/api/offers') return send(res, 200, service.offers());
    if (P && p === '/api/offers') return send(res, 201, await service.createOffer(await readJson(req)));
    if (G && (m = /^\/api\/offers\/(o-\d{4})$/.exec(p))) return send(res, 200, await service.inspectOffer(m[1]));
    if (P && (m = /^\/api\/offers\/(o-\d{4})\/decision$/.exec(p))) return send(res, 200, await service.decide(m[1], await readJson(req)));
    if (P && (m = /^\/api\/offers\/(o-\d{4})\/withdraw$/.exec(p))) return send(res, 200, await service.withdraw(m[1], await readJson(req)));
    if (G && p === '/api/ledger') return send(res, 200, await service.ledger());
    if (G && p === '/api/testnet') return send(res, 200, await service.testnet(url.searchParams.get('live') === '1'));
    if (G && p === '/api/audit') return send(res, 200, service.audit());
    return send(res, 404, {error: 'not found'});
  }

  // Fix inbox #106: a public read of the network (a GET under /pilot/v1/ with no token) may be read from any origin, its
  // error answers too (a 404, a 429, a 503 with retry_after_ms): a profile page or a badge on another site needs no
  // proxy. A request that carries a token never gets the header, and a script on another origin cannot add one without
  // a preflight, which this server never grants. A HEAD gets the headers its GET gets (fix inbox #142). null: no CORS
  // header.
  function publicRead(req) {
    let p = '';
    try { p = new URL(req.url, 'http://x').pathname; } catch { return null; }
    return (req.method === 'GET' || req.method === 'HEAD') && !req.headers.authorization && p.startsWith('/pilot/v1/') ? {'Access-Control-Allow-Origin': '*'} : null;
  }

  return async (req, res) => {
    try { await route(req, res); } catch (e) {
      const cors = publicRead(req) || {};
      if (e instanceof UserError) return send(res, e.code, {error: e.message}, undefined, cors);
      if (e.name === 'PilotError') return send(res, e.status, {error: e.code, message: e.message, ...(e.extra || {})}, undefined, cors);
      console.error(`[${new Date().toISOString()}] ${req.method} ${req.url}: ${e.message}`);
      // Tracker and signer failures get their own code and a fixed, non-secret message (OQ-35); a signer outage is a 503
      // (OQ-31). The details stay in the log line above.
      if (e.name === 'BasisError') {
        const status = e.code === 'signer_unavailable' ? 503 : 502;
        return send(res, status, String(req.url).startsWith('/pilot/') ? {error: e.code, message: e.publicMessage} : {error: e.publicMessage, code: e.code}, undefined, cors);
      }
      send(res, 502, {error: 'internal error'}, undefined, cors);
    }
  };
}
